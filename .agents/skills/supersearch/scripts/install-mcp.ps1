<#
.SYNOPSIS
    Dynamically builds (if needed), installs the SuperSearch skill globally, and prints MCP configuration.
.DESCRIPTION
    1. Resolves the repository root dynamically relative to this script ($PSScriptRoot).
    2. Automatically runs build.bat if bin\supersearch.exe has not been compiled yet.
    3. Optionally adds the repository bin\ directory to the current user's PATH (-AddToPath).
    4. Copies the skill package into ~/.gemini/config/skills/supersearch and injects the resolved
       machine-specific binary path into the global SKILL.md copy (keeping the Git repository clean).
    5. Prints the ready-to-use mcpServers JSON block generated by supersearch.exe --mcp-config.
#>
param(
    [switch]$SkipGlobalSkill,
    [switch]$AddToPath
)

$ErrorActionPreference = "Stop"

$SkillRoot   = Split-Path -Parent $PSScriptRoot
$ProjectRoot = (Resolve-Path (Join-Path $SkillRoot "..\..\..")).Path
$BinDir      = Join-Path $ProjectRoot "bin"
$SuperExe    = Join-Path $BinDir "supersearch.exe"

if (-not (Test-Path $SuperExe)) {
    $BuildBat = Join-Path $ProjectRoot "build.bat"
    if (Test-Path $BuildBat) {
        Write-Host "[INFO] supersearch.exe not found. Building from source..." -ForegroundColor Yellow
        Push-Location $ProjectRoot
        try {
            cmd.exe /c "build.bat"
        } finally {
            Pop-Location
        }
    }
    if (-not (Test-Path $SuperExe)) {
        throw "supersearch.exe not found at $SuperExe. Please run build.bat first."
    }
}

if ($AddToPath) {
    $UserPath = [Environment]::GetEnvironmentVariable("Path", "User")
    $PathEntries = ($UserPath -split ";") | Where-Object { $_ -ne "" }
    if ($PathEntries -notcontains $BinDir) {
        $NewUserPath = ($PathEntries + $BinDir) -join ";"
        [Environment]::SetEnvironmentVariable("Path", $NewUserPath, "User")
        $env:Path = "$env:Path;$BinDir"
        Write-Host "[OK] Added '$BinDir' to User PATH." -ForegroundColor Green
    } else {
        Write-Host "[OK] '$BinDir' is already in User PATH." -ForegroundColor Green
    }
}

if (-not $SkipGlobalSkill) {
    $GlobalSkillsDir = Join-Path $env:USERPROFILE ".gemini\config\skills\supersearch"
    New-Item -ItemType Directory -Path $GlobalSkillsDir -Force | Out-Null
    Copy-Item -Path "$SkillRoot\*" -Destination $GlobalSkillsDir -Recurse -Force

    # Dynamically bind the resolved binary path inside the global skill copy
    $GlobalSkillMd = Join-Path $GlobalSkillsDir "SKILL.md"
    if (Test-Path $GlobalSkillMd) {
        $Content = Get-Content -Path $GlobalSkillMd -Raw -Encoding UTF8
        $ResolvedHeader = "**Binary Resolution:**`r`n- Resolved Binary Path on this machine: ``$SuperExe```r`n- If ``supersearch.exe`` is on ``PATH``, invoke ``supersearch.exe``; otherwise invoke ``$SuperExe``."
        $Content = [regex]::Replace(
            $Content,
            '(?s)\*\*Binary Resolution:\*\*.*?(?=\r?\n\r?\nSuperSearch is a native C)',
            $ResolvedHeader
        )
        Set-Content -Path $GlobalSkillMd -Value $Content -Encoding UTF8 -NoNewline
    }

    Write-Host "[OK] Installed SuperSearch skill globally to: $GlobalSkillsDir" -ForegroundColor Green
    Write-Host "     Bound global skill binary path to      : $SuperExe" -ForegroundColor DarkGray
}

Write-Host "`n[INFO] MCP Server Configuration (Claude Code / Cursor / Windsurf / Antigravity):" -ForegroundColor Cyan
& $SuperExe --mcp-config
